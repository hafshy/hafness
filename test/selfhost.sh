#!/usr/bin/env bash
# Self-host check: the shipped template produces a harness that passes its own gate, the
# run-log writer, history hook and board emit files the lint accepts, the scope fence holds,
# and the plugin/skills are well-formed.
# ponytail: assert-style bash, no framework. Add a case when a real run breaks something.
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TPL="$ROOT/skills/hafness-init/template"
fail() { printf '  FAIL: %b\n' "$*"; exit 1; }

# 1. manifest parses and names the plugin
python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); assert d["name"]=="hafness"' \
  "$ROOT/.claude-plugin/plugin.json" || fail "plugin.json invalid"

# 2. every skill has frontmatter name == its directory
for d in "$ROOT"/skills/*/; do
  n="$(basename "$d")"
  grep -qx "name: $n" "$d/SKILL.md" || fail "skills/$n/SKILL.md frontmatter name != $n"
done
[ "$(ls -d "$ROOT"/skills/*/ | wc -l)" -eq 7 ] || fail "expected 7 skills"

# 3. the shipped scripts and this repo's copies are the same scripts
for s in verify.sh board.sh history.sh; do
  cmp -s "$ROOT/.hafness/$s" "$TPL/.hafness/$s" || fail "template $s drifted from root"
done

# 4. a fresh project from the template passes its own gate once one check exists
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
cp -R "$TPL/." "$tmp/"
H="$tmp/.hafness"
[ -d "$H" ] || fail "template copy lost .hafness/"
perl -pi -e 's/^HAF_STACK=""/HAF_STACK="test"/; s/^HAF_TEST=""/HAF_TEST="true"/' "$H/profile.sh"
out="$(bash "$H/verify.sh" --log F-001 1 3 2>&1)"; rc=$?
[ $rc -eq 0 ] || fail "fresh template gate failed:\n$out"
grep -q 'HAFNESS_VERIFY: PASS' <<<"$out" || fail "no PASS verdict"
grep -q 'HAFNESS_RUN: r-0001' <<<"$out" || fail "first run should be r-0001, got: $(grep HAFNESS_RUN <<<"$out")"
out="$(bash "$H/verify.sh" --log F-001 2 3 2>&1)"
grep -q 'HAFNESS_RUN: r-0002' <<<"$out" || fail "second run should be r-0002"
bash "$H/verify.sh" >/dev/null 2>&1 || fail "written run block failed the grammar lint"

# 5. the history hook tags Hafness commands, prints nothing, and its entries pass the lint
hook() { python3 -c 'import json,sys; print(json.dumps({"prompt": sys.argv[1]}))' "$1" | bash "$H/history.sh"; }
[ -z "$(hook '/hafness-describe an app that tracks habits')" ] || fail "history hook printed to stdout"
hook '/hafness:hafness-plan F-001' >/dev/null
hook $'just a question\n## with a heading inside' >/dev/null
grep -q '· `describe`$' "$H/history.md" || fail "describe prompt not tagged"
grep -q '· `plan`$' "$H/history.md" || fail "plugin-form prompt not tagged"
grep -q '· prompt$' "$H/history.md" || fail "plain prompt not logged"
bash "$H/verify.sh" >/dev/null 2>&1 || fail "history entries failed the lint"

# 6. the board embeds the markdown and is regenerated by the hook
[ -f "$H/board.html" ] || fail "hook did not draw the board"
grep -q 'data-path="history.md"' "$H/board.html" || fail "board is missing history.md"
grep -q 'data-path="log/' "$H/board.html" || fail "board is missing the run log"
printf '# F-001 — Demo\n\nStatus: draft\n\n## Summary\nhas </script> inside\n' > "$H/specs/F-001.md"
bash "$H/board.sh" >/dev/null
grep -q 'data-path="specs/F-001.md"' "$H/board.html" || fail "board is missing the spec"
[ "$(grep -c '</script>' "$H/board.html")" -eq "$(grep -c '<script' "$H/board.html")" ] || fail "a document broke out of its script block"

# 7. the format lint catches drift in specs and tasks
bash "$H/verify.sh" >/dev/null 2>&1 || fail "valid spec failed the lint"
perl -pi -e 's/^Status: draft/Status: finished/' "$H/specs/F-001.md"
bash "$H/verify.sh" >/dev/null 2>&1 && fail "unknown spec status passed the lint"
perl -pi -e 's/^Status: finished/Status: planned/' "$H/specs/F-001.md"
echo '| T-001 | F-001 | Build it | done | `src/` | — |' >> "$H/tasks.md"
bash "$H/verify.sh" >/dev/null 2>&1 && fail "done task without a run id passed the lint"

# 8. the scope fence fails on a change outside every doing task's Scope
perl -pi -e 's/^\| T-001 \| F-001 \| Build it \| done/| T-001 | F-001 | Build it | doing/' "$H/tasks.md"
git -C "$tmp" init -q && git -C "$tmp" add -A && git -C "$tmp" -c user.email=t@t -c user.name=t commit -qm base
mkdir -p "$tmp/src" && echo x > "$tmp/src/a.txt"
bash "$H/verify.sh" >/dev/null 2>&1 || fail "change inside Scope failed the fence"
echo x > "$tmp/elsewhere.txt"
out="$(bash "$H/verify.sh" 2>&1)" && fail "change outside Scope passed the fence"
grep -q 'elsewhere.txt' <<<"$out" || fail "fence did not name the stray file"

# 9. a template with nothing runnable must refuse to pass
mkdir "$tmp/empty" && cp -R "$TPL/." "$tmp/empty/"
bash "$tmp/empty/.hafness/verify.sh" >/dev/null 2>&1 && fail "empty profile passed the gate"

echo "  selfhost ok"
