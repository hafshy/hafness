#!/usr/bin/env bash
# Self-host check: the shipped template produces a harness that passes its own gate, the
# run-log writer, history hook and board emit files the lint accepts, the scope fence holds,
# and the plugin/skills are well-formed.
# ponytail: assert-style bash, no framework. Add a case when a real run breaks something.
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TPL="$ROOT/skills/hafness-init/template"
fail() { printf '  FAIL: %b\n' "$*"; exit 1; }

# 1. manifest parses and names the plugin
python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); assert d["name"]=="hafness"' \
  "$ROOT/.claude-plugin/plugin.json" || fail "plugin.json invalid"

# 2. every skill has frontmatter name == its directory
for d in "$ROOT"/skills/*/; do
  n="$(basename "$d")"
  grep -qx "name: $n" "$d/SKILL.md" || fail "skills/$n/SKILL.md frontmatter name != $n"
done
[ "$(ls -d "$ROOT"/skills/*/ | wc -l)" -eq 8 ] || fail "expected 8 skills"

# 3. the shipped scripts and this repo's copies are the same scripts
for s in verify.sh board.sh history.sh; do
  cmp -s "$ROOT/.hafness/$s" "$TPL/.hafness/$s" || fail "template $s drifted from root"
done

# 4. a fresh project from the template passes its own gate once one check exists
tmp="$(mktemp -d)"; logs="$(mktemp -d)"; trap 'rm -rf "$tmp" "$logs"' EXIT
export TMPDIR="$logs"  # failing gate runs below keep their logs; clean them up with the rest
cp -R "$TPL/." "$tmp/"
H="$tmp/.hafness"
[ -d "$H" ] || fail "template copy lost .hafness/"
perl -pi -e 's/^HAF_STACK=""/HAF_STACK="test"/; s/^HAF_TEST=""/HAF_TEST="true"/' "$H/profile.sh"
out="$(bash "$H/verify.sh" --log F-001 2>&1)"; rc=$?
[ $rc -eq 0 ] || fail "fresh template gate failed:\n$out"
grep -q 'HAFNESS_VERIFY: PASS' <<<"$out" || fail "no PASS verdict"
grep -q 'HAFNESS_RUN: r-0001' <<<"$out" || fail "first run should be r-0001, got: $(grep HAFNESS_RUN <<<"$out")"
out="$(bash "$H/verify.sh" --log F-001 2>&1)"
grep -q 'HAFNESS_RUN: r-0002 · attempt 1/3 · PASS' <<<"$out" || fail "second run should be r-0002 · attempt 1/3 · PASS, got: $(grep HAFNESS_RUN <<<"$out")"
bash "$H/verify.sh" >/dev/null 2>&1 || fail "written run block failed the grammar lint"

# 4b. the gate counts attempts itself: failures climb to ESCALATED, a PASS resets the count
perl -pi -e 's/^HAF_TEST="true"/HAF_TEST="false"/' "$H/profile.sh"
for i in 1 2 3; do bash "$H/verify.sh" --log F-001 >/dev/null 2>&1; done
tail -n 4 "$H"/log/[0-9]*.md | grep -q 'F-001 · attempt 3/3 · ESCALATED' || fail "third failure did not escalate"
perl -pi -e 's/^HAF_TEST="false"/HAF_TEST="true"/' "$H/profile.sh"
bash "$H/verify.sh" --log F-001 >/dev/null 2>&1
grep -q 'F-001 · attempt 4/3 · PASS' "$H"/log/[0-9]*.md || fail "attempt after escalation should be 4"
bash "$H/verify.sh" --log F-001 >/dev/null 2>&1
grep -q 'r-0007 · .* · F-001 · attempt 1/3 · PASS' "$H"/log/[0-9]*.md || fail "a PASS did not reset the attempt count"

# 5. the history hook tags Hafness commands, prints nothing, and its entries pass the lint
hook() { python3 -c 'import json,sys; print(json.dumps({"prompt": sys.argv[1]}))' "$1" | bash "$H/history.sh"; }
[ -z "$(hook '/hafness-describe an app that tracks habits')" ] || fail "history hook printed to stdout"
hook '/hafness:hafness-plan F-001' >/dev/null
hook $'just a question\n## with a heading inside' >/dev/null
grep -q '· `describe`$' "$H/history.md" || fail "describe prompt not tagged"
grep -q '· `plan`$' "$H/history.md" || fail "plugin-form prompt not tagged"
grep -q '· prompt$' "$H/history.md" || fail "plain prompt not logged"
bash "$H/verify.sh" >/dev/null 2>&1 || fail "history entries failed the lint"

# 6. the board embeds the markdown and is regenerated by the hook
[ -f "$H/board.html" ] || fail "hook did not draw the board"
grep -q 'data-path="history.md"' "$H/board.html" || fail "board is missing history.md"
grep -q 'data-path="log/' "$H/board.html" || fail "board is missing the run log"
printf '# F-001 — Demo\n\nStatus: draft\n\n## Summary\nhas </script> inside\n' > "$H/specs/F-001.md"
bash "$H/board.sh" >/dev/null
grep -q 'data-path="specs/F-001.md"' "$H/board.html" || fail "board is missing the spec"
[ "$(grep -c '</script>' "$H/board.html")" -eq "$(grep -c '<script' "$H/board.html")" ] || fail "a document broke out of its script block"
# 6b. the board hook redraws silently for edits under .hafness/, and ignores the rest
rm -f "$H/board.html"
[ -z "$(echo '{"tool_input":{"file_path":"/elsewhere/a.swift"}}' | bash "$H/board.sh" --hook)" ] || fail "board hook printed"
[ ! -f "$H/board.html" ] || fail "board hook redrew for a file outside .hafness/"
[ -z "$(echo "{\"tool_input\":{\"file_path\":\"$H/tasks.md\"}}" | bash "$H/board.sh" --hook)" ] || fail "board hook printed"
[ -f "$H/board.html" ] || fail "board hook did not redraw after a .hafness/ edit"
echo 'not json' | bash "$H/board.sh" --hook || fail "board hook exited non-zero"

# 7. the format lint catches drift in specs and tasks
bash "$H/verify.sh" >/dev/null 2>&1 || fail "valid spec failed the lint"
perl -pi -e 's/^Status: draft/Status: finished/' "$H/specs/F-001.md"
bash "$H/verify.sh" >/dev/null 2>&1 && fail "unknown spec status passed the lint"
perl -pi -e 's/^Status: finished/Status: planned/' "$H/specs/F-001.md"
echo '| T-001 | F-001 | Build it | done | `src/` | — |' >> "$H/tasks.md"
bash "$H/verify.sh" >/dev/null 2>&1 && fail "done task without a run id passed the lint"
perl -pi -e 's/^(\| T-001 .*)\| — \|$/$1| r-9999 |/' "$H/tasks.md"
bash "$H/verify.sh" >/dev/null 2>&1 && fail "done task with an invented run id passed the lint"
perl -pi -e 's/r-9999/r-0003/' "$H/tasks.md"
bash "$H/verify.sh" >/dev/null 2>&1 && fail "done task citing a FAIL run passed the lint"
perl -pi -e 's/r-0003/r-0001/' "$H/tasks.md"
bash "$H/verify.sh" >/dev/null 2>&1 || fail "done task citing a PASS run failed the lint"

# 7b. a spec is done only when every one of its tasks is
perl -pi -e 's/^Status: planned/Status: done/' "$H/specs/F-001.md"
bash "$H/verify.sh" >/dev/null 2>&1 || fail "done spec with every task done failed the lint"
echo '| T-002 | F-001 | Polish it | todo | `src/` | — |' >> "$H/tasks.md"
out="$(bash "$H/verify.sh" 2>&1)" && fail "done spec with a todo task passed the lint"
grep -q 'F-001: done, but not every task is: T-002' <<<"$out" || fail "lint did not name the open task"
perl -ni -e 'print unless /^\| T-002 /' "$H/tasks.md"
perl -pi -e 's/^Status: done/Status: planned/' "$H/specs/F-001.md"

# 8. the scope fence fails on a change outside every doing task's Scope
perl -pi -e 's/^\| T-001 \| F-001 \| Build it \| done \| (.*) \| r-0001 \|$/| T-001 | F-001 | Build it | doing | $1 | — |/' "$H/tasks.md"
git -C "$tmp" init -q && git -C "$tmp" add -A && git -C "$tmp" -c user.email=t@t -c user.name=t commit -qm base
mkdir -p "$tmp/src" && echo x > "$tmp/src/a.txt"
bash "$H/verify.sh" >/dev/null 2>&1 || fail "change inside Scope failed the fence"
echo x > "$tmp/elsewhere.txt"
out="$(bash "$H/verify.sh" 2>&1)" && fail "change outside Scope passed the fence"
grep -q 'elsewhere.txt' <<<"$out" || fail "fence did not name the stray file"
rm "$tmp/elsewhere.txt"
echo '# loosened' >> "$H/profile.sh"
out="$(bash "$H/verify.sh" 2>&1)" && fail "editing profile.sh mid-task passed the fence"
grep -q '.hafness/profile.sh' <<<"$out" || fail "fence did not name profile.sh"
git -C "$tmp" checkout -q -- .hafness/profile.sh

# 8b. HAF_PATHS skips a check whose paths saw no change; --all runs it; a hung check times out
rm -f "$tmp/elsewhere.txt"
printf '\nHAF_EXTRA=("web|echo web-ran")\nHAF_PATHS=("web|web/")\n' >> "$H/profile.sh"
git -C "$tmp" add -A && git -C "$tmp" -c user.email=t@t -c user.name=t commit -qm paths
echo y > "$tmp/src/a.txt"
out="$(bash "$H/verify.sh" 2>&1)"
grep -q 'skipped — nothing changed under web/' <<<"$out" || fail "a check with untouched paths ran:\n$out"
out="$(bash "$H/verify.sh" --all 2>&1)"
grep -A1 -- '--- web' <<<"$out" | grep -q '    ok' || fail "--all did not run the web check:\n$out"
printf 'HAF_TIMEOUT_MIN=0\nHAF_EXTRA=("hang|sleep 30")\nHAF_PATHS=()\n' >> "$H/profile.sh"
out="$(bash "$H/verify.sh" 2>&1)" && fail "a hung check passed"
grep -q 'timed out' <<<"$out" || fail "a hung check was not reported as timed out:\n$out"
grep -q 'Terminated' <<<"$out" && fail "the timeout leaked a job notice"
pgrep -f 'sleep 30$' >/dev/null && fail "a timed-out check left its process running"

# 8c. a check named in HAF_SLOW is skipped until --slow, and the log says so
printf 'HAF_TIMEOUT_MIN=20\nHAF_EXTRA=("journey|echo journey-ran")\nHAF_SLOW=("journey")\n' >> "$H/profile.sh"
git -C "$tmp" add -A && git -C "$tmp" -c user.email=t@t -c user.name=t commit -qm slow
echo z > "$tmp/src/a.txt"
out="$(bash "$H/verify.sh" --log F-001 2>&1)"
grep -q 'skipped — slow' <<<"$out" || fail "a slow check ran without --slow:\n$out"
grep -q 'skipped, slow: journey' "$H"/log/[0-9]*.md || fail "the run block does not name the skipped slow check"
out="$(bash "$H/verify.sh" --slow 2>&1)"
grep -A1 -- '--- journey' <<<"$out" | grep -q '    ok' || fail "--slow did not run the slow check:\n$out"

# 8d. a fast PASS between failing slow runs does not reset the attempt count
commit() { git -C "$tmp" add -A && git -C "$tmp" -c user.email=t@t -c user.name=t commit -qm "$1"; echo z$RANDOM > "$tmp/src/a.txt"; }
perl -pi -e 's/journey-ran/journey-ran; false/' "$H/profile.sh"; commit slow-fails
bash "$H/verify.sh" --log F-002 >/dev/null 2>&1
out="$(bash "$H/verify.sh" --log F-002 --slow 2>&1)"
grep -q 'attempt 1/3 · FAIL' <<<"$out" || fail "first slow failure should be attempt 1: $(grep HAFNESS_RUN <<<"$out")"
bash "$H/verify.sh" --log F-002 >/dev/null 2>&1
out="$(bash "$H/verify.sh" --log F-002 --slow 2>&1)"
grep -q 'attempt 2/3 · FAIL' <<<"$out" || fail "a fast PASS reset the count: $(grep HAFNESS_RUN <<<"$out")"
perl -pi -e 's/journey-ran; false/journey-ran/' "$H/profile.sh"; commit slow-passes

printf 'HAF_SLOW=("journy")\n' >> "$H/profile.sh"
out="$(bash "$H/verify.sh" 2>&1)" && fail "a misspelt HAF_SLOW label passed"
grep -q 'names a check that does not exist: journy' <<<"$out" || fail "the stray label was not named:\n$out"

# 9. a template with nothing runnable must refuse to pass
mkdir "$tmp/empty" && cp -R "$TPL/." "$tmp/empty/"
bash "$tmp/empty/.hafness/verify.sh" >/dev/null 2>&1 && fail "empty profile passed the gate"

echo "  selfhost ok"
